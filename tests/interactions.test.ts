import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { PGLiteSocketServer } from '@electric-sql/pglite-socket';
import { NextRequest } from 'next/server';
import { hashPassword } from 'better-auth/crypto';
import { db } from '../src/lib/server/db';
import { createAuth } from '../src/lib/server/auth';
import { setLike } from '../src/lib/server/http';
import { GET as reactions } from '../src/app/api/writing/[slug]/reactions/route';
import { GET as comments, POST as submit } from '../src/app/api/writing/[slug]/comments/route';
import { PUT as like } from '../src/app/api/writing/[slug]/like/route';
import { PATCH as review } from '../src/app/api/admin/comments/[id]/route';

test('shared interactions, moderation, authentication and quotas against embedded PostgreSQL', {timeout: 90000}, async () => {
  const pg = await PGlite.create();
  const server = new PGLiteSocketServer({db: pg, port: 0, host: '127.0.0.1', maxConnections: 4});
  const slug = `test-${randomUUID()}`; const fixture = path.join(process.cwd(), 'content/writing', slug);
  const originalEnv = {...process.env};
  try {
    await pg.exec(fs.readFileSync('prisma/migrations/202610210001_writing/migration.sql', 'utf8'));
    await server.start();
    process.env.DATABASE_URL = `postgresql://postgres:postgres@${server.getServerConn()}/postgres?connection_limit=1&sslmode=disable`;
    process.env.BETTER_AUTH_SECRET = 'test-only-secret-with-more-than-32-characters';
    process.env.BETTER_AUTH_URL = 'http://localhost:3000'; process.env.TRUST_PROXY = '1';
    fs.mkdirSync(fixture);
    fs.writeFileSync(path.join(fixture, 'zh.md'), '---\ntitle: Test fixture\nsummary: Not production content\ncategory: tech\ndate: "2026-10-21"\ndraft: false\n---\n## Test\n\nFixture body.');
    const params = {params: Promise.resolve({slug})};
    const request = (endpoint: string, method = 'GET', data?: unknown, cookie = '', ip = '192.0.2.1') => new NextRequest(`http://localhost:3000/api/writing/${slug}/${endpoint}`, {method, headers: {'origin': 'http://localhost:3000', 'content-type': 'application/json', cookie, 'x-real-ip': ip}, ...(data ? {body: JSON.stringify(data)} : {})});
    await db().$queryRaw`SELECT 1`;
    const response = await reactions(request('reactions'), params);
    assert.equal(response.status, 200);
    const cookie = response.cookies.get('gy-writing-visitor')!;
    const browser = `${cookie.name}=${cookie.value}`;
    const visitor = cookie.value.split('.')[0];
    assert.equal((await like(request('like', 'PUT', {liked: true}, browser), params)).status, 200);
    await Promise.all(Array.from({length: 8}, () => setLike(slug, visitor, true)));
    assert.equal(await db().like.count({where: {slug}}), 1);
    const other = await reactions(request('reactions'), params);
    assert.equal((await other.json()).likes, 1);
    assert.equal((await submit(request('comments', 'POST', {nickname: 'Visitor', text: 'Shared comment'}, browser), params)).status, 202);
    assert.equal((await comments(request('comments'), params)).status, 200);
    assert.equal((await (await comments(request('comments'), params)).json()).items.length, 0);
    const pending = await db().comment.findFirstOrThrow({where: {slug}});
    const reviewParams = {params: Promise.resolve({id: pending.id})};
    assert.equal((await review(request('review','PATCH',{status: 'APPROVED'},browser),reviewParams)).status, 403);
    const id = randomUUID();
    await db().user.create({data: {id, name: 'Admin', email: 'admin@example.test', role: 'admin', emailVerified: true}});
    await db().account.create({data: {id: randomUUID(), userId: id, accountId: id, providerId: 'credential', password: await hashPassword('test-password-12345')}});
    const auth = createAuth();
    const login = await auth.handler(new Request('http://localhost:3000/api/auth/sign-in/email', {method: 'POST', headers: {'content-type': 'application/json', origin: 'http://localhost:3000', 'x-real-ip': '192.0.2.20'}, body: JSON.stringify({email: 'admin@example.test',password: 'test-password-12345'})}));
    assert.equal(login.status, 200, await login.clone().text());
    const adminCookie = login.headers.getSetCookie().map(c => c.split(';')[0]).join('; ');
    assert.ok(adminCookie);
    const userId = randomUUID();
    await db().user.create({data: {id: userId, name: 'User', email: 'user@example.test'}});
    await db().account.create({data: {id: randomUUID(), userId, accountId: userId, providerId: 'credential', password: await hashPassword('test-user-password-12345')}});
    const userLogin = await auth.handler(new Request('http://localhost:3000/api/auth/sign-in/email', {method: 'POST', headers: {'content-type': 'application/json', origin: 'http://localhost:3000', 'x-real-ip': '192.0.2.21'}, body: JSON.stringify({email: 'user@example.test',password: 'test-user-password-12345'})}));
    assert.equal(userLogin.status, 200);
    const userCookie = userLogin.headers.getSetCookie().map(c => c.split(';')[0]).join('; ');
    assert.equal((await review(request('review','PATCH',{status: 'APPROVED'},userCookie),reviewParams)).status, 403);
    const registration = await auth.handler(new Request('http://localhost:3000/api/auth/sign-up/email', {method: 'POST', headers: {'content-type': 'application/json', origin: 'http://localhost:3000'}, body: JSON.stringify({name: 'Intruder',email:'intruder@example.test',password:'test-password-12345',role:'admin'})}));
    assert.ok(registration.status >= 400);
    // A real authenticated administrator can approve and hide, with an audit trail.
    assert.equal((await review(request('review','PATCH',{status: 'APPROVED'},adminCookie),reviewParams)).status, 200);
    const visible = await (await comments(request('comments'), params)).json();
    assert.equal(visible.items.length, 1); assert.equal(visible.items[0].text, 'Shared comment');
    assert.equal('visitorId' in visible.items[0], false);
    assert.equal((await review(request('review','PATCH',{status: 'HIDDEN'},adminCookie),reviewParams)).status, 200);
    assert.equal((await (await comments(request('comments'), params)).json()).items.length, 0);
    assert.equal(await db().review.count(), 2);
    assert.equal((await submit(request('comments','POST',{nickname: 'Visitor',text: 'Too soon'},browser),params)).status, 429);
    assert.equal((await submit(request('comments','POST',{nickname: '',text: 'Invalid'},browser),params)).status, 400);
    const badOrigin = request('like','PUT',{liked:true},browser); badOrigin.headers.set('origin','https://evil.test');
    assert.equal((await like(badOrigin,params)).status, 403);
    assert.equal((await reactions(request('reactions'),{params:Promise.resolve({slug: 'not-published'})})).status, 404);
    assert.equal((await like(request('like','PUT',{liked:false},browser),params)).status, 200);
    assert.equal(await db().like.count(), 0);
    await db().comment.createMany({data: Array.from({length: 21}, (_, index) => ({slug, visitorId: visitor, nickname: 'Pagination', text: `Comment ${index}`, status: 'APPROVED'}))});
    const firstPage = await (await comments(request('comments'),params)).json();
    assert.equal(firstPage.items.length, 20); assert.ok(firstPage.nextCursor);
    const pageRequest = request('comments'); pageRequest.nextUrl.searchParams.set('cursor', firstPage.nextCursor);
    const secondPage = await (await comments(pageRequest,params)).json();
    assert.equal(secondPage.items.length, 1); assert.equal(secondPage.nextCursor, null);
    assert.ok(!firstPage.items.some((c: {id: string}) => c.id === secondPage.items[0].id));
    // Disconnect and reconnect the client: records outlive application connections.
    await db().$disconnect();
    assert.equal(await db().comment.count(), 22);
  } finally {
    if (process.env.DATABASE_URL) await db().$disconnect();
    fs.rmSync(fixture, {recursive: true, force: true});
    await server.stop(); await pg.close();
    process.env = originalEnv;
  }
});
